#!/usr/bin/env bash
# Host prerequisite for the optional NVIDIA GPU embedding service.
set -euo pipefail
if [[ $EUID -ne 0 ]]; then
  echo "Run this installer with sudo: sudo bash scripts/install_nvidia_toolkit.sh" >&2
  exit 1
fi
command -v nvidia-smi >/dev/null
nvidia-smi --query-gpu=name,driver_version,memory.total --format=csv,noheader
temporary_dir="$(mktemp -d)"
trap 'rm -rf -- "$temporary_dir"' EXIT
apt-get update
apt-get install -y --no-install-recommends ca-certificates curl gnupg
curl -fsSL https://nvidia.github.io/libnvidia-container/gpgkey -o "$temporary_dir/key"
gpg --batch --yes --dearmor -o "$temporary_dir/keyring.gpg" "$temporary_dir/key"
install -m 0644 "$temporary_dir/keyring.gpg" /usr/share/keyrings/nvidia-container-toolkit-keyring.gpg
curl -fsSL https://nvidia.github.io/libnvidia-container/stable/deb/nvidia-container-toolkit.list \
  | sed 's#deb https://#deb [signed-by=/usr/share/keyrings/nvidia-container-toolkit-keyring.gpg] https://#g' \
  > "$temporary_dir/toolkit.list"
install -m 0644 "$temporary_dir/toolkit.list" /etc/apt/sources.list.d/nvidia-container-toolkit.list
apt-get update
apt-get install -y --no-install-recommends nvidia-container-toolkit
# CDI is generated by Toolkit 1.18+ and is native in Docker Engine 28.3+.
# No Docker daemon restart or legacy --gpus registration is needed.
systemctl enable --now nvidia-cdi-refresh.path
systemctl restart nvidia-cdi-refresh.service
nvidia-ctk cdi list
docker info --format '{{json .CDISpecDirs}}' | python3 -c \
  'import json,sys; sys.exit(0 if json.load(sys.stdin) else "Docker CDI is unavailable; use a CDI-enabled Docker Engine (28.3+ recommended).")'
echo 'NVIDIA Container Toolkit installed and CDI devices generated. Run make hardware.'
